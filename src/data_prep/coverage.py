"""Write data/coverage.md. Usage: python -I coverage.py <project_dir>"""
import gzip, json, sys
import xml.etree.ElementTree as ET
from pathlib import Path


def decode_rows(codec, rows, lead_offset):
    out = []
    for r in rows:
        for c in range(0xA1, 0xFF):
            try:
                out.append(bytes([r + lead_offset, c]).decode(codec))
            except UnicodeDecodeError:
                pass
    return out


def main(root):
    d = root / "data"
    load = lambda p: {json.loads(l)["ch"]: json.loads(l)["src"] for l in open(p, encoding="utf-8")}
    have, ja = load(d / "skeletons.jsonl"), load(d / "skeletons_ja.jsonl")
    joyo = [c.findtext("literal") for c in
            ET.parse(gzip.open(d / "raw/kanjidic2/kanjidic2.xml.gz")).getroot().iter("character")
            if c.findtext("misc/grade") in set("12345678")]
    sets = {
        "(a) GB2312 hanzi": decode_rows("gb2312", range(16, 88), 0xA0),
        "(b) JIS X 0208 level 1+2 kanji": decode_rows("euc_jp", range(16, 85), 0xA0),
        "(c) hiragana + katakana (JIS X 0208 rows 4-5)": decode_rows("euc_jp", (4, 5), 0xA0),
        "(d) 常用漢字 (KANJIDIC2 grades 1-8)": joyo,
    }
    lines = ["# Coverage", "",
             "Generated by `src/data_prep/coverage.py`. Charsets come from Python codecs except 常用漢字,",
             "which has no codec. It comes from KANJIDIC2 grades 1-8 (`data/raw/kanjidic2/`).", "",
             "Coordinates in `skeletons*.jsonl`: MMAH font units. em 1024, y up, baseline y=0,",
             "em box x 0..1024, y -124..900. MMAH medians unchanged. KanjiVG: x*1024/109, 900 - y*1024/109.", "",
             "| set | total | covered | mmah | kanjivg | missing | KanjiVG JP form available |",
             "|---|---|---|---|---|---|---|"]
    details = []
    for name, chars in sets.items():
        cov = [c for c in chars if c in have]
        miss = [c for c in chars if c not in have]
        nm = sum(have[c] == "mmah" for c in cov)
        lines.append(f"| {name} | {len(chars)} | {len(cov)} | {nm} | {len(cov) - nm} | {len(miss)} | "
                     f"{sum(c in ja for c in chars)} |")
        if not name.startswith("(b)"):
            shown = "".join(miss[:300]) + (f" … (+{len(miss) - 300})" if len(miss) > 300 else "")
            details += ["", f"## Missing {name}: {len(miss)}", "", shown or "(none)"]
    (d / "coverage.md").write_text("\n".join(lines + details) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main(Path(sys.argv[1]).resolve())
